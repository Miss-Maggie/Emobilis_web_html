# arithmmetic operators
x=5
y=7
print(x+y)  #addition
print(x-y)  #substraction
print(x*y)  #multiplication
print(x/y)  #division
print(x//y) #floor division
print(x%y) #reminder
print(x**y) #exponention

#comparison operators
print(x == y)   #equal to
print(x != y)   #not equal to
print(x < y)    #less than
print(x <= y)   #less than or equals to
print(x > y)    #greater than
print(x >= y)   #greater than

#logical operators
print(x > 4 and y < 10)  #and
print(x > 4 or  y < 10)  #or
print(not(x > 4 or y < 10))
